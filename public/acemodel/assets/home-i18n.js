export function applyHomeLanguage(doc, language) {
  const copy = homeCopy[language] || homeCopy.zh;
  doc.documentElement.lang = documentLanguage(language);
  doc.title = copy.title;
  for (const element of doc.querySelectorAll('[data-i18n]')) {
    const value = copy[element.getAttribute('data-i18n')];
    if (value !== undefined) element.textContent = value;
  }
  for (const attribute of ['aria-label', 'alt', 'content']) {
    for (const element of doc.querySelectorAll(`[data-i18n-${attribute}]`)) {
      const value = copy[element.getAttribute(`data-i18n-${attribute}`)];
      if (value !== undefined) element.setAttribute(attribute, value);
    }
  }
}

if (typeof window !== 'undefined' && typeof document !== 'undefined') {
  const updateLanguage = () => applyHomeLanguage(document, browserLanguage(navigator));
  updateLanguage();
  window.addEventListener('languagechange', updateLanguage);
}
